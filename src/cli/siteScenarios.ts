function captureRun(): {
  logger: { info(m: string): void; error(m: string): void };
  lines: string[];
} {
  const lines: string[] = [];
  return {
    logger: { info: (m: string) => lines.push(m), error: (m: string) => lines.push(m) },
    lines,
  };
}

function redact(line: string, targetDir: string, tmpDir: string): string {
  return line.split(targetDir).join("<target>").split(tmpDir).join("<tmp>");
}

async function buildRealScenario(spec: RealSpec): Promise<FlowScenario> {
  const base = {
    id: spec.id,
    title: spec.title,
    kind: "real" as const,
    surface: spec.surface,
    command: spec.command,
    note: spec.note,
  };

  if (spec.withTarget === false) {
    const { logger, lines } = captureRun();
    const exitCode = await run([...spec.argv], { logger });
    return { ...base, exitCode, lines: lines.flatMap((line) => line.split("\n")) };
  }

  const tmpDir = mkdtempSync(path.join(os.tmpdir(), "aig-scenario-"));
  const targetDir = path.join(tmpDir, "repo");
  try {
    mkdirSync(targetDir, { recursive: true });
    spec.seed?.(targetDir);
    const { logger, lines } = captureRun();
    const exitCode = await run([...spec.argv, "--target", targetDir], { logger });
    return {
      ...base,
      exitCode,
      lines: lines
        .flatMap((line) => line.split("\n"))
        .map((line) => redact(line, targetDir, tmpDir)),
    };
  } finally {
    rmSync(tmpDir, { recursive: true, force: true });
  }
}

function buildGuidedScenario(spec: GuidedSpec): FlowScenario {
  // Fidelidade: o NOME do comando exibido tem de existir no registry real.
  const exists = siteCommandSurface().some((command) => command.name === spec.commandName);
  if (!exists) {
    throw new Error(`siteScenarios: comando guiado "${spec.commandName}" não existe no registry.`);
  }
  return {
    id: spec.id,
    title: spec.title,
    kind: "guided",
    surface: spec.surface,
    command: spec.command,
    note: spec.note,
    exitCode: null,
    lines: spec.lines,
  };
}

export async function buildSiteScenarios(): Promise<readonly FlowScenario[]> {
  const real: FlowScenario[] = [];
  for (const spec of REAL_SPECS) {
    real.push(await buildRealScenario(spec));
  }
  const guided = GUIDED_SPECS.map(buildGuidedScenario);
  return [...real, ...guided];
}

export async function renderSiteScenariosScript(): Promise<string> {
  const scenarios = await buildSiteScenarios();
  return `// ${GENERATED_NOTICE}\n// prettier-ignore\nexport const AI_GUIDELINES_FLOW_SCENARIOS = ${JSON.stringify(
    scenarios,
    null,
    2
  )} as const;\n`;
}

export async function syncSiteScenarios(repoRoot: string): Promise<void> {
  const outputPath = siteScenariosOutputPath(repoRoot);
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, await renderSiteScenariosScript(), "utf-8");
}

export async function checkSiteScenarios(repoRoot: string): Promise<readonly string[]> {
  const outputPath = siteScenariosOutputPath(repoRoot);
  const expected = await renderSiteScenariosScript();
  if (!existsSync(outputPath)) {
    return [`${OUTPUT_RELATIVE_PATH} não existe; rode npm run site:scenarios:sync`];
  }
  const actual = readFileSync(outputPath, "utf-8");
  if (actual !== expected) {
    return [
      `${OUTPUT_RELATIVE_PATH} diverge dos transcripts do runtime; rode npm run site:scenarios:sync`,
    ];
  }
  return [];
}

export async function main(
  argv: readonly string[] = process.argv.slice(2),
  repoRoot = process.cwd(),
  logger: Logger = console
): Promise<number> {
  const command = argv[0] ?? "check";
  if (command === "sync") {
    await syncSiteScenarios(repoRoot);
    logger.log(`✅ site:scenarios:sync — ${OUTPUT_RELATIVE_PATH} gerado do runtime real.`);
    return 0;
  }
  if (command === "check") {
    const violations = await checkSiteScenarios(repoRoot);
    if (violations.length > 0) {
      logger.error(
        "❌ site:scenarios:check encontrou drift entre o site e os transcripts do runtime:\n" +
          violations.map((violation) => `  - ${violation}`).join("\n")
      );
      return 1;
    }
    logger.log("✅ site:scenarios:check — transcripts do site sincronizados com o runtime.");
    return 0;
  }
  logger.error("Uso: node dist/cli/siteScenarios.js [check|sync]");
  return 2;
}

if (require.main === module) {
  void main().then((exitCode) => {
    if (exitCode !== 0) process.exitCode = exitCode;
  });
}
