/**
 * Gerador de cenários de terminal do site (B2 — "terminal não pode mentir").
 *
 * Cada cenário tem uma SUPERFÍCIE:
 *  - public      → consumidor do framework (`npx ai-guidelines …`);
 *  - contributor → quem contribui no próprio repo ai-guidelines (`npm run flow …`).
 *
 * E uma CLASSE de procedência:
 *  - real   → stdout capturado de execução real (dry-run/--help). Determinístico.
 *  - guided → linhas curadas, genéricas e consumer-safe; o NOME do comando é
 *             validado contra o registry (fidelidade), os exemplos não vazam
 *             identificadores internos (PR/spec/sub-checkpoint).
 *
 * O site exibe `kind` como badge e usa `surface` para separar perfis.
 */

const GENERATED_NOTICE = "Generated by npm run site:scenarios:sync. Do not edit manually.";
const OUTPUT_RELATIVE_PATH = "site/src/generated/flow-scenarios.generated.ts";

type Logger = Pick<typeof console, "error" | "log">;

export type ScenarioKind = "real" | "guided";
export type ScenarioSurface = "public" | "contributor";

export interface FlowScenario {
  readonly id: string;
  readonly title: string;
  readonly kind: ScenarioKind;
  readonly surface: ScenarioSurface;
  readonly command: string;
  readonly note: string;
  readonly exitCode: number | null;
  readonly lines: readonly string[];
}

export function siteScenariosOutputPath(repoRoot: string): string {
  return path.join(repoRoot, OUTPUT_RELATIVE_PATH);
}

interface RealSpec {
  readonly id: string;
  readonly title: string;
  readonly surface: ScenarioSurface;
  readonly command: string;
  readonly note: string;
  /** argv passado ao runtime real. `--target` é injetado quando `withTarget`. */
  readonly argv: readonly string[];
  readonly withTarget?: boolean;
  readonly seed?: (targetDir: string) => void;
}

interface GuidedSpec {
  readonly id: string;
  readonly title: string;
  readonly surface: ScenarioSurface;
  /** Invocação exibida (consumer-safe / genérica). */
  readonly command: string;
  /** Nome canônico do comando — validado contra o registry (fidelidade). */
  readonly commandName: string;
  readonly note: string;
  /** Linhas curadas (genéricas). Prefixo já incluso (`$ npx …` / texto). */
  readonly lines: readonly string[];
}

