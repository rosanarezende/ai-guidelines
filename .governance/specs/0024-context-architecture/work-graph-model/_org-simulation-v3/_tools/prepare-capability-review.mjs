// prepare-capability-review.mjs — gera pacotes de revisao para AI-assisted capability extraction.
// Nao chama LLM. O runtime fica deterministico; a IA e canal de autoria assistida.
// Uso:
//   node _tools/prepare-capability-review.mjs --write
//   node _tools/prepare-capability-review.mjs --check
//   node _tools/prepare-capability-review.mjs --repo acme-checkout --write
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import { parse } from "yaml";
import { REPOS_ROOT } from "./org.mjs";
import { inspectRepoCode } from "./repo-contexts.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(here, "..");
const REPOS = REPOS_ROOT;
const TEMPLATE = path.join(ROOT, "_templates", "capability-extraction-prompt.md");
const args = process.argv.slice(2);
const write = args.includes("--write");
const check = args.includes("--check");
const repoFilter = args.includes("--repo") ? args[args.indexOf("--repo") + 1] : null;

if (!write && !check) {
  console.error("Uso: node _tools/prepare-capability-review.mjs --write|--check [--repo <repo>]");
  process.exit(2);
}

const readYaml = (file) => parse(readFileSync(file, "utf8"));
const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));

function digest(value) {
  return createHash("sha256").update(value).digest("hex").slice(0, 12);
}

function repoDirs() {
  return readdirSync(REPOS)
    .map((name) => path.join(REPOS, name))
    .filter((full) => statSync(full).isDirectory() && existsSync(path.join(full, "package.json")))
    .filter((full) => !repoFilter || path.basename(full) === repoFilter)
    .sort();
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listFiles(full));
    else if (full.endsWith(".mjs")) out.push(full);
  }
  return out.sort();
}

function exportSnippets(repoDir) {
  const files = listFiles(path.join(repoDir, "src"));
  const snippets = [];
  const exportLine = /^\s*export\s+/;
  for (const file of files) {
    const lines = readFileSync(file, "utf8").split(/\r?\n/);
    const selected = lines
      .map((line, index) => ({ line, index: index + 1 }))
      .filter(({ line }) => exportLine.test(line))
      .slice(0, 12);
    if (selected.length === 0) continue;
    snippets.push({
      file: path.relative(repoDir, file).replaceAll("\\", "/"),
      lines: selected,
    });
  }
  return snippets;
}

function yamlBlock(value) {
  return `\`\`\`yaml\n${value.trim()}\n\`\`\``;
}

function jsonBlock(value) {
  return `\`\`\`json\n${JSON.stringify(value, null, 2)}\n\`\`\``;
}

async function renderReview(repoDir, outPath) {
  const repo = path.basename(repoDir);
  const pkg = readJson(path.join(repoDir, "package.json"));
  const manifestPath = path.join(repoDir, ".governance", "manifest.yml");
  const candidatePath = path.join(repoDir, ".governance", "capability-candidates.yml");
  const contextPath = path.join(repoDir, ".governance", "context.json");
  const manifestRaw = existsSync(manifestPath) ? readFileSync(manifestPath, "utf8") : "";
  const candidateRaw = existsSync(candidatePath) ? readFileSync(candidatePath, "utf8") : "";
  const context = existsSync(contextPath) ? readJson(contextPath) : null;
  const code = inspectRepoCode(repoDir);
  const snippets = exportSnippets(repoDir);
  const template = readFileSync(TEMPLATE, "utf8").trim();
  const evidenceHash = digest(
    JSON.stringify({
      pkg,
      manifestRaw,
      candidateRaw,
      contextHash: context?.contentHash || null,
      code,
      snippets,
    })
  );

  const snippetText =
    snippets.length === 0
      ? "_No exported source snippets found._"
      : snippets
          .map(
            (s) =>
              `### ${s.file}\n\n\`\`\`js\n${s.lines
                .map(({ line, index }) => `${String(index).padStart(3, " ")}: ${line}`)
                .join("\n")}\n\`\`\``
          )
          .join("\n\n");

  const markdown = `# Capability Review Packet — ${repo}

> Generated by \`prepare-capability-review.mjs\`.
> Evidence hash: \`${evidenceHash}\`.
> Status: advisory packet. Do not treat AI output as attested truth.

## How To Use

1. Send this packet to an AI assistant together with the task below.
2. Ask for a manifest patch proposal only.
3. A human owner reviews the proposal.
4. Only reviewed changes go into \`.governance/manifest.yml\`.
5. Run \`node _tools/publish-contexts.mjs && node _tools/check-repo-contexts.mjs\`.

## Prompt Contract

${template}

## Repository Input

${jsonBlock({
  repo,
  package: {
    name: pkg.name,
    dependencies: Object.keys({
      ...(pkg.dependencies || {}),
      ...(pkg.devDependencies || {}),
    }).sort(),
  },
  code,
})}

## Current Manifest

${manifestRaw ? yamlBlock(manifestRaw) : "_No manifest yet._"}

## Deterministic Candidate

${candidateRaw ? yamlBlock(candidateRaw) : "_No capability candidate yet._"}

## Published Context Summary

${context ? jsonBlock({ schema: context.schema, repo: context.repo, contentHash: context.contentHash, provides: context.provides, consumes: context.consumes, capabilities: context.capabilities }) : "_No context.json yet._"}

## Source Export Evidence

${snippetText}
`;
  const prettierOptions = (await prettier.resolveConfig(outPath)) || {};
  return prettier.format(markdown, { ...prettierOptions, parser: "markdown" });
}

let changed = 0;
let missing = 0;
const dirs = repoDirs();
if (repoFilter && dirs.length === 0) {
  console.error(`repo nao encontrado: ${repoFilter}`);
  process.exit(2);
}

for (const repoDir of dirs) {
  const repo = path.basename(repoDir);
  const out = path.join(repoDir, ".governance", "capability-review.md");
  const expected = await renderReview(repoDir, out);
  const current = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (check) {
    if (current !== expected) {
      console.error(
        `${current === null ? "missing" : "stale"} capability review: ${path.relative(ROOT, out)}`
      );
      missing++;
    }
    continue;
  }
  if (current !== expected) {
    mkdirSync(path.dirname(out), { recursive: true });
    writeFileSync(out, expected);
    changed++;
  }
  console.log(`capability review: ${repo}`);
}

if (check && missing > 0) {
  console.error(`capability review packets stale/missing: ${missing}`);
  process.exit(1);
}

console.log(
  check ? "capability review packets: ok" : `capability review packets: ok (${changed} updated)`
);
